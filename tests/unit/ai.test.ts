import { describe, expect, it } from "vitest";
import { AI_LABEL, formatCredits, MEMBER_NOTICE, stateNote, TURN_ON_NOTICE } from "@/lib/ai";

describe("ai", () => {
  it("stateNote maps each code to copy and link", () => {
    expect(stateNote("ai_disabled", "owner")).toEqual({ text: "Turn on Dashboard AI", href: "/settings/ai" });
    expect(stateNote("ai_disabled", "member")).toEqual({ text: "Ask an owner to turn on Dashboard AI" });
    expect(stateNote("ai_unavailable", "owner")).toEqual({ text: "Dashboard AI isn't available yet." });
    expect(stateNote("ai_key_failing", "member")).toEqual({
      text: "Your AI key isn't working. Replace or remove it in AI settings.",
    });
    expect(stateNote("ai_quota_reached", "owner")).toEqual({
      text: "This period's AI credits are used up. Buy a top-up or add your own key.",
      href: "/settings/ai",
    });
    expect(stateNote("ready", "owner")).toBeNull();
    expect(stateNote(undefined, "owner")).toBeNull();
  });
  it("formatCredits shows two decimals", () => {
    expect(formatCredits("1000")).toBe("1,000.00");
    expect(formatCredits("0.0049")).toBe("0.00");
    expect(formatCredits("12.345")).toBe("12.35");
  });
  it("fixed copy is verbatim", () => {
    expect(TURN_ON_NOTICE).toBe(
      "Dashboard AI sends the details of the findings and resources you ask about to Anthropic to generate answers. Anthropic does not train on this data. You can turn it off at any time, or use your own OpenAI or Anthropic key instead.",
    );
    expect(MEMBER_NOTICE).toBe("Ask an owner to turn on Dashboard AI");
    expect(AI_LABEL).toBe("Generated by AI: may be wrong");
  });
});
