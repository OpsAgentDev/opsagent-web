import { describe, expect, it } from "vitest";
import type { AiKey, AiStatus } from "@/lib/api/client";
import { AI_LABEL, backupServing, formatCredits, keyLine, MEMBER_NOTICE, stateNote, TURN_ON_NOTICE } from "@/lib/ai";

const key = (over: Partial<AiKey> = {}): AiKey => ({
  style: "anthropic", base_host: null, last4: "1234", status: "ok", models: { routine: "r", chat: "c" }, ...over,
});
const withKeys = (primary: AiKey | null, backup: AiKey | null) => ({ keys: { primary, backup } }) as AiStatus;

describe("ai", () => {
  it("stateNote maps each code to copy and link", () => {
    expect(stateNote("ai_disabled", "owner")).toEqual({ text: "Turn on Dashboard AI", href: "/settings/ai" });
    expect(stateNote("ai_disabled", "member")).toEqual({ text: "Ask an owner to turn on Dashboard AI" });
    expect(stateNote("ai_unavailable", "owner")).toEqual({ text: "Dashboard AI isn't available yet." });
    expect(stateNote("ai_key_failing", "owner")).toEqual({
      text: "Your AI key isn't working. Replace or remove it in AI settings.",
    });
    expect(stateNote("ai_key_failing", "member")).toEqual({
      text: "Your organisation's AI key isn't working. Ask an owner to replace or remove it.",
    });
    expect(stateNote("ai_quota_reached", "member")).toEqual({
      text: "This period's AI credits are used up. Ask an owner to buy a top-up or add a key.",
    });
    expect(stateNote("ai_quota_reached", "owner")).toEqual({
      text: "This period's AI credits are used up. Buy a top-up or add your own key.",
      href: "/settings/ai",
    });
    expect(stateNote("ready", "owner")).toBeNull();
    expect(stateNote(undefined, "owner")).toBeNull();
  });
  it("formatCredits shows two decimals", () => {
    expect(formatCredits("1000")).toBe("1,000.00");
    expect(formatCredits("0.0049")).toBe("0.00");
    expect(formatCredits("12.345")).toBe("12.35");
  });
  it("fixed copy is verbatim", () => {
    expect(TURN_ON_NOTICE).toBe(
      "Dashboard AI sends the details of the findings and resources you ask about to Anthropic, or to the AI provider you configure, to generate answers. Anthropic does not train on this data. You can turn it off at any time, or use your own OpenAI or Anthropic key instead.",
    );
    expect(MEMBER_NOTICE).toBe("Ask an owner to turn on Dashboard AI");
    expect(AI_LABEL).toBe("Generated by AI: may be wrong");
  });
  it("stateNote maps ai_model_invalid", () => {
    expect(stateNote("ai_model_invalid", "owner")).toEqual({
      text: "Your AI key's model isn't available. Pick another model in AI settings.",
      href: "/settings/ai",
    });
    expect(stateNote("ai_model_invalid", "member")).toEqual({
      text: "Your organisation's AI model isn't available. Ask an owner to pick another.",
    });
  });
  it("keyLine shows style, host and status", () => {
    expect(keyLine(key())).toBe("Your Anthropic-compatible key ending 1234: ok");
    expect(keyLine(key({ style: "openai", base_host: "gw.example", status: "provider_outage" }))).toBe(
      "Your OpenAI-compatible key ending 1234 at gw.example: provider outage",
    );
    expect(keyLine(key({ status: "failing" }))).not.toContain(" at ");
  });
  it("backupServing only when primary failing and backup not", () => {
    expect(backupServing(withKeys(key({ status: "failing" }), key()))).toBe(true);
    expect(backupServing(withKeys(key({ status: "failing" }), key({ status: "provider_outage" })))).toBe(true);
    expect(backupServing(withKeys(key({ status: "failing" }), key({ status: "failing" })))).toBe(false);
    expect(backupServing(withKeys(key({ status: "failing" }), null))).toBe(false);
    expect(backupServing(withKeys(key(), key()))).toBe(false);
    expect(backupServing(withKeys(null, null))).toBe(false);
  });
});
