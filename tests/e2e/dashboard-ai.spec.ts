import { expect, test } from "@playwright/test";
import { connectNoisy, signUp, sql } from "./helpers";

const NOTICE =
  "Dashboard AI sends the details of the findings and resources you ask about to Anthropic to generate answers. Anthropic does not train on this data. You can turn it off at any time, or use your own OpenAI or Anthropic key instead.";
const NEWEST_ORG = "(SELECT id FROM organisations ORDER BY created_at DESC LIMIT 1)";

test("owner turns on AI after reading the notice", async ({ page, request }) => {
  await signUp(page, request);
  await page.goto("/settings/ai");
  await expect(page.getByText(NOTICE)).toBeVisible();
  const toggle = page.getByLabel("Dashboard AI on");
  await expect(toggle).not.toBeChecked();
  await toggle.click(); // controlled: it flips once brain answers
  await expect(toggle).toBeChecked();
  await expect(page.getByText("Provider: Anthropic, on OpsAgent's key")).toBeVisible();
  await page.reload();
  await expect(page.getByLabel("Dashboard AI on")).toBeChecked();
  await expect(page.getByText(/^Resets on /)).toBeVisible();
});

test("explain a finding shows label and cached text on reload", async ({ page, request }) => {
  await signUp(page, request);
  await connectNoisy(page);
  sql(`UPDATE organisations SET ai_enabled = true WHERE id = ${NEWEST_ORG}`);
  await page.goto("/findings");
  const link = page.locator("tbody tr a").first();
  await expect(async () => {
    await page.reload();
    await expect(link).toBeVisible({ timeout: 2_000 });
  }).toPass({ timeout: 60_000 });
  await link.click();
  await expect(page).toHaveURL(/\/findings\/[0-9a-f-]+$/);
  const id = page.url().split("/").pop();
  await expect(page.getByRole("link", { name: "Ask about this finding" })).toHaveAttribute("href", `/chat?finding=${id}`);
  await page.getByRole("button", { name: "Explain this finding" }).click();
  await expect(page.getByText("Generated by AI: may be wrong")).toBeVisible();
  await expect(page.getByText(/What it means/)).toBeVisible();

  await page.reload();
  await expect(page.getByText("Generated by AI: may be wrong")).toBeVisible();
  await expect(page.getByText(/What it means/)).toBeVisible();
  await expect(page.getByRole("button", { name: "Explain this finding" })).toHaveCount(0);

  await page.getByRole("button", { name: "Report a wrong explanation" }).click();
  await page.getByLabel("What is wrong?").fill("It names the wrong service.");
  await page.getByRole("button", { name: "Send report" }).click();
  await expect(page.getByText("Thanks. We'll look at it.")).toBeVisible();
});

