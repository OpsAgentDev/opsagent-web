// Dashboard AI copy (verbatim per the spec), the four refusal states and credit formatting.
export const TURN_ON_NOTICE =
  "Dashboard AI sends the details of the findings and resources you ask about to Anthropic to generate answers. Anthropic does not train on this data. You can turn it off at any time, or use your own OpenAI or Anthropic key instead.";
export const MEMBER_NOTICE = "Ask an owner to turn on Dashboard AI";
export const AI_LABEL = "Generated by AI: may be wrong";

/** BYOK providers and their display names. */
export const PROVIDERS: Record<string, string> = { anthropic: "Anthropic", openai: "OpenAI" };

export type StateNote = { text: string; href?: string };

/** The copy and next action for brain's AI refusal codes (and `AiStatusOut.state`); null when ready. */
export function stateNote(code: string | undefined, role: string): StateNote | null {
  switch (code) {
    case "ai_disabled":
      return role === "owner" ? { text: "Turn on Dashboard AI", href: "/settings/ai" } : { text: MEMBER_NOTICE };
    case "ai_unavailable":
      return { text: "Dashboard AI isn't available yet." };
    case "ai_key_failing":
      return { text: "Your AI key isn't working. Replace or remove it in AI settings." };
    case "ai_quota_reached":
      return { text: "This period's AI credits are used up. Buy a top-up or add your own key.", href: "/settings/ai" };
    default:
      return null;
  }
}

/** Brain sends credits as decimal strings; shown with two decimals. */
export function formatCredits(credits: string): string {
  return Number(credits).toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 });
}
