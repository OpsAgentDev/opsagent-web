import type { AiKey, AiStatus } from "@/lib/api/client";

// Dashboard AI copy (verbatim per the spec), the four refusal states and credit formatting.
export const TURN_ON_NOTICE =
  "Dashboard AI sends the details of the findings and resources you ask about to Anthropic, or to the AI provider you configure, to generate answers. Anthropic does not train on this data. You can turn it off at any time, or use your own OpenAI or Anthropic key instead.";
export const MEMBER_NOTICE = "Ask an owner to turn on Dashboard AI";
export const AI_LABEL = "Generated by AI: may be wrong";

/** BYOK API styles and their display names. */
export const STYLES: Record<string, string> = { anthropic: "Anthropic-compatible", openai: "OpenAI-compatible" };
/** Each style's own API, used when the base URL is left empty. */
export const OFFICIAL_URLS: Record<string, string> = {
  anthropic: "https://api.anthropic.com",
  openai: "https://api.openai.com/v1",
};

/** One saved key's status line: style, last 4, custom host when set, status. */
export function keyLine(k: AiKey): string {
  return `Your ${STYLES[k.style]} key ending ${k.last4}${k.base_host ? ` at ${k.base_host}` : ""}: ${k.status.replace("_", " ")}`;
}

/** The backup is serving: the primary is failing and a backup that is not failing exists. */
export function backupServing(s: AiStatus): boolean {
  const { primary, backup } = s.keys;
  return primary?.status === "failing" && !!backup && backup.status !== "failing";
}

export type StateNote = { text: string; href?: string };

/** The copy and next action for brain's AI refusal codes (and `AiStatusOut.state`); null when ready. */
export function stateNote(code: string | undefined, role: string): StateNote | null {
  switch (code) {
    case "ai_disabled":
      return role === "owner" ? { text: "Turn on Dashboard AI", href: "/settings/ai" } : { text: MEMBER_NOTICE };
    case "ai_unavailable":
      return { text: "Dashboard AI isn't available yet." };
    case "ai_key_failing":
      return role === "owner"
        ? { text: "Your AI key isn't working. Replace or remove it in AI settings." }
        : { text: "Your organisation's AI key isn't working. Ask an owner to replace or remove it." };
    case "ai_model_invalid":
      return role === "owner"
        ? { text: "Your AI key's model isn't available. Pick another model in AI settings.", href: "/settings/ai" }
        : { text: "Your organisation's AI model isn't available. Ask an owner to pick another." };
    case "ai_quota_reached":
      return role === "owner"
        ? { text: "This period's AI credits are used up. Buy a top-up or add your own key.", href: "/settings/ai" }
        : { text: "This period's AI credits are used up. Ask an owner to buy a top-up or add a key." };
    default:
      return null;
  }
}

/** Brain sends credits as decimal strings; shown with two decimals. */
export function formatCredits(credits: string): string {
  return Number(credits).toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 });
}
